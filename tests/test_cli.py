import json

from conftest import needs_glslang

from ghostfx.cli import detect_colorspace, main


def run(capsys, *argv):
    rc = main(list(argv))
    out = capsys.readouterr()
    return rc, out.out, out.err


def test_list_search_info_json(sandbox, capsys):
    rc, out, _ = run(capsys, "list", "--json")
    assert rc == 0 and len(json.loads(out)) >= 180
    rc, out, _ = run(capsys, "search", "portal", "--json")
    ids = [x["id"] for x in json.loads(out)]
    assert "ender-portal" in ids and "nether-portal" in ids
    rc, out, _ = run(capsys, "info", "ender-portal", "--json")
    assert json.loads(out)["category"] == "minecraft"
    rc, out, _ = run(capsys, "categories", "--json")
    assert sum(json.loads(out).values()) >= 180


@needs_glslang
def test_apply_current_disable_uninstall(sandbox, capsys):
    home, cfg = sandbox
    cfg.write_text("font-size = 12\n")
    rc, out, _ = run(capsys, "apply", "nebula", "--preset", "subtle", "--no-reload", "--json")
    assert rc == 0, out
    data = json.loads(out)
    assert data["backup"] and (home / "shaders" / "nebula.glsl").exists()
    assert "custom-shader = " in cfg.read_text()
    rc, out, _ = run(capsys, "current", "--json")
    assert json.loads(out)["current"] == "nebula"
    rc, _, err = run(capsys, "uninstall", "nebula", "--yes")
    assert rc == 1 and "currently applied" in err
    assert run(capsys, "disable", "--no-reload")[0] == 0
    assert cfg.read_text() == "font-size = 12\n"
    assert run(capsys, "uninstall", "nebula", "--yes")[0] == 0
    assert not (home / "shaders" / "nebula.glsl").exists()


def test_apply_dry_run_and_foreign_shader_protection(sandbox, capsys):
    _, cfg = sandbox
    cfg.write_text("custom-shader = /mine.glsl\n")
    rc, _, err = run(capsys, "apply", "fog", "--no-reload")
    assert rc == 1 and "--replace" in err
    rc, out, _ = run(capsys, "apply", "fog", "--replace", "--dry-run", "--no-reload")
    assert rc == 0 and "ghostfx-disabled" in out
    assert cfg.read_text() == "custom-shader = /mine.glsl\n"


def test_refuses_to_overwrite_foreign_file(sandbox, capsys):
    home, _ = sandbox
    (home / "shaders").mkdir(parents=True)
    (home / "shaders" / "fog.glsl").write_text("// my own shader\n")
    rc, _, err = run(capsys, "install", "fog")
    assert rc == 1 and "not written by GhostFX" in err


def test_home_manager_config_gets_declarative_snippet(sandbox, capsys):
    _, cfg = sandbox
    cfg.write_text("# Generated by Home Manager\n")
    rc, out, _ = run(capsys, "apply", "fog", "--no-reload")
    assert rc == 3 and "programs.ghostfx" in out


def test_presets_favorites_export(sandbox, capsys, tmp_path):
    home, _ = sandbox
    assert run(capsys, "preset", "create", "mine", "--shader", "ender-portal")[0] == 0
    p = home / "presets" / "mine.toml"
    assert 'name = "ender-portal"' in p.read_text()
    rc, out, _ = run(capsys, "preset", "list", "--json")
    assert json.loads(out)["user"]["mine"] == "ender-portal"
    assert run(capsys, "favorite", "ender-portal")[0] == 0
    rc, out, _ = run(capsys, "favorites", "--json")
    assert json.loads(out) == ["ender-portal"]
    out_file = tmp_path / "x.glsl"
    assert run(capsys, "export", "--preset", "mine", "-o", str(out_file))[0] == 0
    assert "ender-portal" in out_file.read_text()


def test_colorspace_detection():
    assert detect_colorspace("alpha-blending = native\n") == 1
    assert detect_colorspace("alpha-blending = linear-corrected\n") == 2


def test_doctor_runs(sandbox, capsys):
    rc, out, _ = run(capsys, "doctor", "--json")
    assert rc == 0 and any(c["check"] == "config" for c in json.loads(out))
