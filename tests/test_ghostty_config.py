import os
import stat

import pytest

from ghostfx import ghostty

BASE = "font-size = 13\ntheme = dark\n"


def test_apply_appends_managed_block_and_is_idempotent():
    new = ghostty.plan_apply(BASE, ["/s/a.glsl"])
    assert ghostty.BEGIN in new and "custom-shader = /s/a.glsl" in new
    again = ghostty.plan_apply(new, ["/s/b.glsl"])
    assert again.count(ghostty.BEGIN) == 1
    assert "/s/a.glsl" not in again and "/s/b.glsl" in again
    assert again.startswith(BASE)


def test_foreign_shader_requires_explicit_choice():
    text = BASE + "custom-shader = /mine.glsl\n"
    with pytest.raises(ghostty.ConfigError):
        ghostty.plan_apply(text, ["/s/a.glsl"])
    chained = ghostty.plan_apply(text, ["/s/a.glsl"], chain=True)
    assert "\ncustom-shader = /mine.glsl\n" in chained
    replaced = ghostty.plan_apply(text, ["/s/a.glsl"], replace_foreign=True)
    assert ghostty.DISABLED + "custom-shader = /mine.glsl" in replaced
    restored = ghostty.plan_disable(replaced, restore=True)
    assert restored == text


def test_disable_removes_only_the_block():
    applied = ghostty.plan_apply(BASE, ["/s/a.glsl"], animation="always")
    assert "custom-shader-animation = always" in applied
    assert ghostty.plan_disable(applied) == BASE


def test_write_backup_and_rollback(sandbox):
    home, cfg = sandbox
    cfg.write_text(BASE)
    os.chmod(cfg, 0o640)
    b = ghostty.write_config(cfg, ghostty.plan_apply(BASE, ["/s/a.glsl"]))
    assert b and b.read_text() == BASE
    assert stat.S_IMODE(cfg.stat().st_mode) == 0o640           # permissions preserved
    src, target = ghostty.rollback()
    assert target == cfg and cfg.read_text() == BASE


def test_dry_run_writes_nothing(sandbox):
    _, cfg = sandbox
    cfg.write_text(BASE)
    ghostty.write_config(cfg, "changed\n", dry_run=True)
    assert cfg.read_text() == BASE


def test_home_manager_configs_are_never_edited(sandbox, tmp_path):
    _, cfg = sandbox
    cfg.write_text("# Generated by Home Manager.\nfont-size = 12\n")
    assert ghostty.is_nix_managed(cfg)
    with pytest.raises(ghostty.ManagedByNix):
        ghostty.write_config(cfg, "x\n")
    ro = tmp_path / "ro"
    ro.write_text(BASE)
    os.chmod(ro, 0o444)
    if os.geteuid() != 0:                                       # root ignores modes
        assert ghostty.is_nix_managed(ro)


def test_read_state(sandbox):
    _, cfg = sandbox
    cfg.write_text(ghostty.plan_apply(BASE + "custom-shader = /x.glsl\n", ["/s/a.glsl"], chain=True))
    st = ghostty.read_state(cfg)
    assert st.managed_shaders == ["/s/a.glsl"] and st.foreign_shaders == ["/x.glsl"]
