#!/usr/bin/env python3
"""Regenerate docs/IMPLEMENTATION_STATUS.md from manifest.json,
tests/verification.json and benchmarks/results.json (facts only)."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))


man = json.loads((ROOT / "manifest.json").read_text())
ver = json.loads((ROOT / "tests" / "verification.json").read_text()) if (ROOT / "tests" / "verification.json").exists() else {"shaders": {}}
bench_path = ROOT / "benchmarks" / "results.json"
bench = json.loads(bench_path.read_text()) if bench_path.exists() else {}
catalog = [w for line in (ROOT / "tests" / "catalog.txt").read_text().splitlines() if not line.startswith("#") for w in line.split()]
shaders = man["shaders"]
V = ver.get("shaders", {})

rendered = [s["id"] for s in shaders if V.get(s["id"], {}).get("ghostty_render") == "pass"]
failed = [s["id"] for s in shaders if V.get(s["id"], {}).get("ghostty_render") == "fail"]
untested = [s["id"] for s in shaders if s["id"] not in V]
static_ = [s["id"] for s in shaders if V.get(s["id"], {}).get("animates") is False]
lowc = sorted(((s["id"], V[s["id"]]["contrast"]) for s in shaders if V.get(s["id"], {}).get("contrast") and V[s["id"]]["contrast"] < 4.5), key=lambda x: x[1])
no_thumb = [s["id"] for s in shaders if not (ROOT / "thumbnails" / f"{s['id']}.webp").exists()]
anim = [s["id"] for s in shaders if (ROOT / "previews" / f"{s['id']}.webp").exists()]
limits = [(s["id"], lim) for s in shaders for lim in s["known_limitations"]]
in_catalog = set(catalog)
stretch = [s["id"] for s in shaders if s["id"] not in in_catalog]

out = []
w = out.append
w("# Implementation status")
w("")
w("_Generated by `scripts/status.py`. Only facts recorded in the repository are reported._")
w("")
w("## Summary")
w("")
w("| Item | Status |")
w("|---|---|")
w(f"| Shaders implemented | **{len(shaders)}** ({len([i for i in catalog if any(s['id'] == i for s in shaders)])}/180 catalogue + {len(stretch)} stretch) |")
w(f"| Compile: Ghostty SPIR-V → GLSL 430 + MSL, legacy 1.2, GLSL ES 3.00 | {len(shaders)}/{len(shaders)} (pytest `tests/test_validate.py`, CI on Linux + macOS) |")
w(f"| Rendered in real Ghostty | {len(rendered)}/{len(shaders)} — Ghostty {ver.get('ghostty_version', '?')}, {ver.get('environment', '?')} |")
w(f"| Render failures | {len(failed)} {'(' + ', '.join(failed) + ')' if failed else ''} |")
w(f"| Not yet rendered in Ghostty | {len(untested)} {'(' + ', '.join(untested) + ')' if untested else ''} |")
w("| macOS / Metal runtime | not tested on hardware (MSL cross-compilation verified for all) |")
w(f"| Thumbnails | {len(shaders) - len(no_thumb)}/{len(shaders)} (from the Ghostty captures) |")
w(f"| Animated previews | {len(anim)}/{len(shaders)} |")
bm = bench.get("shaders", {})
w(f"| Benchmarked | {len(bm)} shaders on {bench.get('renderer', 'n/a')} (software rendering, see PERFORMANCE.md); 0 on real GPUs |")
w("")
w("## Components")
w("")
for name, state in [
    ("GLSL library + Ghostty compatibility layer (`glsl/`)", "done"),
    ("Build / preset compiler, palettes, user presets", "done"),
    ("Validator reproducing Ghostty's pipeline", "done"),
    ("CLI: list, search, info, preview, install, apply, export, current, disable, uninstall, categories, palettes, favorites, random, preset list/apply/create/show, config show/edit/validate/path, rollback, validate, build, manifest, benchmark, doctor, update, version, generate-previews, tui", "done"),
    ("Safe config edits: managed block, atomic write, backups, rollback, foreign-shader protection, Home Manager detection, SIGUSR2 reload", "done (tested)"),
    ("Nix flake: package, prebuilt shaders, dev shell, checks, overlay", "done (`nix flake check`, `nix build` run)"),
    ("Home Manager module `programs.ghostfx`", "done (evaluated against Home Manager master)"),
    ("Gallery website (Next.js static export, WebGL2 previews, controls)", "done (builds; all shaders compile in Chromium WebGL2)"),
    ("Real-Ghostty capture + verification pipeline", "done"),
    ("Offscreen renderer + GPU timer benchmarks", "done; GPU numbers pending"),
    ("CI / release / Pages / security workflows", "written; not yet run on GitHub (repository not yet published)"),
]:
    w(f"- {name}: **{state}**")
w("")
w("## Shaders that did not animate visibly in the 3-second capture window")
w("")
w("A second offscreen check (moderngl, 10 frames over 40 s) confirmed motion for each of these: slow drift "
  "(black-hole, planetary-rings, lunar-surface, rusted-steel), intermittent events (crt-glitch, cyber-glitch, lightning, "
  "neon-pulse, glass-prism), focus-triggered intros that settle (boot-sequence, console-startup, crt-power, "
  "crt-terminal-1980), cursor-driven ripples (typing-ripples) and a 1.5% phosphor flicker below the pixel threshold "
  "(green-phosphor). Not yet re-checked in Ghostty itself over a longer window:")
w("")
w(", ".join(static_) if static_ else "none")
w("")
w("## Text contrast below 4.5:1 (measured, balanced preset)")
w("")
if lowc:
    w("| Shader | Contrast |")
    w("|---|---|")
    for i, c in lowc:
        w(f"| {i} | {c}:1 |")
else:
    w("None.")
w("")
w("## Unsupported or approximated effects")
w("")
w("- **No previous-frame feedback** in Ghostty: phosphor persistence (`amber-terminal`, `retro-radar`), trails and accumulation (`snow-accumulation`) are analytic approximations.")
w("- **No mouse input** (`iMouse` is always 0): interactive shaders react to the **cursor** instead (`typing-ripples`, `keyboard-glow`).")
w("- **No access to the desktop behind the window**: glass shaders use procedural backdrops.")
w("- **Cell size is not exposed**: scanlines cannot lock to text rows.")
for i, lim in limits:
    w(f"- `{i}`: {lim}")
w("")
w("## Remaining work")
w("")
w("1. Publish the repository (`r3dg0d/ghostfx`) and let CI run on GitHub runners (Linux + macOS).")
w("2. Benchmark on real GPUs (RTX 4090 at 1920×1080, 2560×1440, 3440×1440, 3840×2160; AMD; Intel; Apple Silicon): `ghostfx benchmark --all --save benchmarks/<gpu>.json`.")
w("3. Run the capture pipeline on macOS (Metal renderer) and record results.")
w("4. Generate animated previews for every shader (`ghostfx generate-previews --all --animated`) and host them outside git (release assets or Pages).")
w("5. Tag v1.0.0 once 1–3 are done; v0.9.0 is the current pre-release.")
w("")
(ROOT / "docs" / "IMPLEMENTATION_STATUS.md").write_text("\n".join(out) + "\n")
print("wrote docs/IMPLEMENTATION_STATUS.md")
