"""Safe edits to the Ghostty configuration file.

GhostFX only ever touches a clearly marked block:

    # >>> ghostfx >>>
    # Managed by GhostFX. Change it with `ghostfx apply` / `ghostfx disable`.
    custom-shader = /home/me/.config/ghostty/ghostfx/shaders/ender-portal.glsl
    # <<< ghostfx <<<

Every write is atomic (temp file + rename in the same directory) and is
preceded by a timestamped backup, so `ghostfx rollback` can undo it.
Other `custom-shader` lines are left alone unless the user passes
`--replace`, in which case they are commented out (never deleted) with a
`# ghostfx-disabled:` prefix that `ghostfx disable --restore` reverts.

Configs that live in the Nix store (Home Manager) are never edited; the
caller gets the declarative snippet to use instead.
"""

from __future__ import annotations

import datetime as _dt
import os
import re
import shutil
import signal
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from .paths import backup_dir, ghostty_config_path

BEGIN = "# >>> ghostfx >>>"
END = "# <<< ghostfx <<<"
DISABLED = "# ghostfx-disabled: "
_SHADER_RE = re.compile(r"^\s*custom-shader\s*=\s*(.*?)\s*$")
_ANIM_RE = re.compile(r"^\s*custom-shader-animation\s*=")


class ConfigError(RuntimeError):
    pass


class ManagedByNix(ConfigError):
    """The config is generated (e.g. by Home Manager) and must not be edited."""


@dataclass
class ConfigState:
    path: Path
    exists: bool
    managed_shaders: list[str]
    foreign_shaders: list[str]
    disabled_shaders: list[str]
    animation: str | None
    nix_managed: bool


def is_nix_managed(path: Path) -> bool:
    try:
        resolved = path.resolve()
    except OSError:
        return False
    if str(resolved).startswith("/nix/store/"):
        return True
    if path.exists() and not os.access(path, os.W_OK):
        return True
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:400]
    except OSError:
        return False
    low = head.lower()
    return "generated by home manager" in low or ("home-manager" in low and "generated" in low)


def _split(text: str) -> tuple[list[str], list[str], list[str]]:
    """Return (before, managed block body, after) lines."""
    lines = text.splitlines()
    try:
        b = lines.index(BEGIN)
        e = lines.index(END, b)
    except ValueError:
        return lines, [], []
    return lines[:b], lines[b + 1 : e], lines[e + 1 :]


def read_state(path: Path | None = None) -> ConfigState:
    path = path or ghostty_config_path()
    exists = path.exists()
    text = path.read_text(encoding="utf-8") if exists else ""
    before, block, after = _split(text)
    managed = [m.group(1) for l in block if (m := _SHADER_RE.match(l))]
    foreign, disabled, anim = [], [], None
    for l in before + after:
        if (m := _SHADER_RE.match(l)):
            foreign.append(m.group(1))
        elif l.startswith(DISABLED) and (m := _SHADER_RE.match(l[len(DISABLED):])):
            disabled.append(m.group(1))
        elif _ANIM_RE.match(l):
            anim = l.split("=", 1)[1].strip()
    for l in block:
        if _ANIM_RE.match(l):
            anim = l.split("=", 1)[1].strip()
    return ConfigState(path, exists, managed, foreign, disabled, anim, is_nix_managed(path))


def backup(path: Path) -> Path | None:
    if not path.exists():
        return None
    d = backup_dir()
    d.mkdir(parents=True, exist_ok=True)
    stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    dest = d / f"{path.name}.{stamp}"
    shutil.copy2(path, dest)
    (d / f"{path.name}.{stamp}.origin").write_text(str(path), encoding="utf-8")
    return dest


def list_backups() -> list[Path]:
    d = backup_dir()
    if not d.is_dir():
        return []
    return sorted((p for p in d.iterdir() if not p.name.endswith(".origin")), key=lambda p: p.name)


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def render_block(shader_paths: list[str], animation: str | None) -> list[str]:
    out = [BEGIN, "# Managed by GhostFX. Change it with `ghostfx apply` / `ghostfx disable`."]
    for s in shader_paths:
        out.append(f"custom-shader = {s}")
    if animation:
        out.append(f"custom-shader-animation = {animation}")
    out.append(END)
    return out


def plan_apply(
    text: str,
    shader_paths: list[str],
    animation: str | None = None,
    replace_foreign: bool = False,
    chain: bool = False,
) -> str:
    """Return the new config text. Pure function: no I/O."""
    before, _block, after = _split(text)
    has_block = BEGIN in text.splitlines()
    rest = before + after
    foreign = [l for l in rest if _SHADER_RE.match(l)]
    if foreign and not (replace_foreign or chain):
        raise ConfigError(
            "your Ghostty config already sets custom-shader outside GhostFX:\n  "
            + "\n  ".join(foreign)
            + "\nGhostty would chain both shaders. Re-run with --replace to comment those lines out "
            "(they are kept and can be restored with `ghostfx disable --restore`), or --chain to keep them."
        )
    if replace_foreign:
        before = [DISABLED + l if _SHADER_RE.match(l) else l for l in before]
        after = [DISABLED + l if _SHADER_RE.match(l) else l for l in after]
    block = render_block(shader_paths, animation)
    if has_block:
        new = before + block + after
    else:
        new = before + after
        if new and new[-1].strip():
            new.append("")
        new += block
    return "\n".join(new) + "\n"


def plan_disable(text: str, restore: bool = False) -> str:
    before, _block, after = _split(text)
    lines = before + after
    if restore:
        lines = [l[len(DISABLED):] if l.startswith(DISABLED) else l for l in lines]
    # Drop a trailing blank line we may have introduced.
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines) + ("\n" if lines else "")


def write_config(path: Path, new_text: str, dry_run: bool = False) -> Path | None:
    if is_nix_managed(path):
        raise ManagedByNix(f"{path} is managed by Nix/Home Manager and is read-only")
    if dry_run:
        return None
    b = backup(path)
    atomic_write(path, new_text)
    return b


def rollback(to: Path | None = None, dry_run: bool = False) -> tuple[Path, Path]:
    backups = list_backups()
    if to is None:
        if not backups:
            raise ConfigError("no GhostFX backups to roll back to")
        to = backups[-1]
    origin_file = to.with_name(to.name + ".origin")
    target = Path(origin_file.read_text().strip()) if origin_file.exists() else ghostty_config_path()
    if is_nix_managed(target):
        raise ManagedByNix(f"{target} is managed by Nix/Home Manager and is read-only")
    if not dry_run:
        backup(target)
        atomic_write(target, to.read_text(encoding="utf-8"))
    return to, target


def reload_ghostty() -> str:
    """Ask running Ghostty instances to reload their configuration.

    Linux (GTK) Ghostty reloads on SIGUSR2. On macOS there is no signal
    API, so the user is told to use the reload keybinding (cmd+shift+,).
    """
    if os.uname().sysname == "Darwin":
        return "press cmd+shift+, in Ghostty to reload the configuration"
    if os.environ.get("GHOSTFX_GHOSTTY_PID"):            # target one instance (tests, scripts)
        pids = [int(x) for x in os.environ["GHOSTFX_GHOSTTY_PID"].split(",") if x.strip()]
    else:
        try:
            out = subprocess.run(["pgrep", "-x", "ghostty"], capture_output=True, text=True)
            pids = [int(p) for p in out.stdout.split()]
        except (OSError, ValueError):
            pids = []
    if not pids:
        return "Ghostty is not running; the shader loads on next start"
    for pid in pids:
        try:
            os.kill(pid, signal.SIGUSR2)
        except OSError:
            pass
    return f"sent SIGUSR2 to {len(pids)} Ghostty process(es) to reload the config"


def home_manager_snippet(shader_id: str, preset: str = "balanced") -> str:
    return (
        "# Your Ghostty config is managed by Home Manager. Add this instead:\n"
        "programs.ghostfx = {\n"
        "  enable = true;\n"
        f'  shader = "{shader_id}";\n'
        f'  preset = "{preset}";\n'
        "};\n"
        "# then run: home-manager switch"
    )
