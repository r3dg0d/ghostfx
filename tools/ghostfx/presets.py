"""Palettes and preset files.

A preset file is a small TOML document (GhostFX's own format, not Ghostty
syntax) that the build step compiles into #defines:

    [shader]
    name = "ender-portal"
    base = "balanced"          # subtle | balanced | cinematic | shader-specific
    intensity = 0.55
    speed = 1.0
    quality = "balanced"       # eco | balanced | ultra
    palette = "cyberpunk-purple"
    reduced_motion = false

    [colors]
    primary = "#8B5CF6"

    [params]                   # shader-specific parameters
    depth = 1.2
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from .meta import COMMON_COLORS, COMMON_PARAMS, MetaError, Shader
from .paths import data_root, user_preset_dir

_SHADER_KEYS = {k.lower() for k in COMMON_PARAMS}


@dataclass
class PresetFile:
    shader: str
    base: str = "balanced"
    overrides: dict = field(default_factory=dict)
    palette: str | None = None
    path: Path | None = None


def list_palettes() -> dict[str, dict]:
    out = {}
    for p in sorted((data_root() / "themes").glob("*.toml")):
        data = tomllib.loads(p.read_text(encoding="utf-8"))
        out[p.stem] = {"name": data.get("name", p.stem), "colors": data.get("colors", {})}
    return out


def load_palette(name: str) -> dict[str, str]:
    pals = list_palettes()
    if name not in pals:
        raise MetaError(f"unknown palette '{name}' (available: {', '.join(pals)})")
    return {k.upper(): v for k, v in pals[name]["colors"].items() if k.upper() in COMMON_COLORS}


def parse_preset(text: str, path: Path | None = None) -> PresetFile:
    where = str(path or "preset")
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise MetaError(f"{where}: invalid TOML: {e}") from e
    sh = data.get("shader") or {}
    name = sh.get("name")
    if not name:
        raise MetaError(f"{where}: [shader] name is required")
    pf = PresetFile(shader=name, base=sh.get("base", "balanced"), palette=sh.get("palette"), path=path)
    for k, v in sh.items():
        if k in ("name", "base", "palette"):
            continue
        if k not in _SHADER_KEYS:
            raise MetaError(f"{where}: unknown [shader] key '{k}'")
        pf.overrides[k.upper()] = v
    for k, v in (data.get("colors") or {}).items():
        if k.upper() not in COMMON_COLORS:
            raise MetaError(f"{where}: unknown colour '{k}'")
        pf.overrides[k.upper()] = str(v)
    for k, v in (data.get("params") or {}).items():
        pf.overrides[k.upper()] = v
    return pf


def load_preset_file(path: Path) -> PresetFile:
    return parse_preset(path.read_text(encoding="utf-8"), path)


def user_presets() -> dict[str, PresetFile]:
    d = user_preset_dir()
    out = {}
    if d.is_dir():
        for p in sorted(d.glob("*.toml")):
            try:
                out[p.stem] = load_preset_file(p)
            except MetaError:
                continue
    return out


def preset_template(shader: Shader, name: str, base: str = "balanced") -> str:
    """A commented starting point for `ghostfx preset create`."""
    from .build import resolve_values

    vals, colors = resolve_values(shader, base)
    lines = [
        f"# GhostFX user preset '{name}' for {shader.name}.",
        "# Apply with: ghostfx preset apply " + name,
        "",
        "[shader]",
        f'name = "{shader.id}"',
        f'base = "{base}"',
    ]
    for k in ("INTENSITY", "SPEED", "BRIGHTNESS", "SATURATION", "OPACITY", "READABILITY"):
        lines.append(f"{k.lower()} = {vals[k][1]}")
    lines.append(f'quality = "{["eco", "balanced", "ultra"][int(vals["QUALITY"][1])]}"')
    lines.append(f"reduced_motion = {'true' if vals['REDUCED_MOTION'][1] else 'false'}")
    lines.append(f"reduced_flash = {'true' if vals['REDUCED_FLASH'][1] else 'false'}")
    lines += ["", "[colors]"]
    for k in ("PRIMARY", "SECONDARY", "ACCENT"):
        lines.append(f'{k.lower()} = "{colors[k]}"')
    if shader.params:
        lines += ["", "[params]"]
        for p in shader.params.values():
            lines.append(f"{p.name.lower()} = {vals[p.name][1]}  # {p.description} [{p.min}..{p.max}]")
    return "\n".join(lines) + "\n"


def default_presets_toml(shader: Shader) -> str:
    """The generated presets/<category>/<id>.toml documenting built-in presets."""
    from .build import resolve_values

    out = [
        f"# GhostFX built-in presets for {shader.name} ({shader.id}).",
        "# Generated by `ghostfx build` - do not edit; copy into a user preset instead.",
        f"# Apply with: ghostfx apply {shader.id} --preset <name>",
        "",
    ]
    for pr in shader.presets:
        vals, colors = resolve_values(shader, pr)
        out.append(f"[presets.{pr}]")
        for k, (typ, v) in vals.items():
            if k.startswith("COLORSPACE"):
                continue
            if typ == "bool":
                out.append(f"{k.lower()} = {'true' if v else 'false'}")
            elif k == "QUALITY":
                out.append(f'quality = "{["eco", "balanced", "ultra"][int(v)]}"')
            else:
                out.append(f"{k.lower()} = {v}")
        out.append(f"[presets.{pr}.colors]")
        for k in ("PRIMARY", "SECONDARY", "ACCENT"):
            out.append(f'{k.lower()} = "{colors[k]}"')
        out.append("")
    return "\n".join(out)
